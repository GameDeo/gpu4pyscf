#!/usr/bin/env python
'''Generate ejk_int3c2e_ip1_f32.cu: an FP32 copy of the DF-gradient Rys derivative kernel (sum_ejk_int3c2e_ip1).
All included sources are inlined into one translation unit inside `namespace rysf32`, `double` becomes `float` and
floating literals get an `f` suffix (so no FP64 arithmetic is left).  The entry point is exported as
sum_ejk_int3c2e_ip1_f32 (same arguments with float in place of double; env must be a float32 copy).
Used for the low tier of the Gamma-weighted precision tiers of the DF J/K gradient (df/grad/rhf.py).
Run: python gen_f32.py   (output is committed; rerun when the double sources change)'''
import os, re
here = os.path.dirname(os.path.abspath(__file__))
libdir = os.path.dirname(here)
seen = set()
SYS = re.compile(r'#include\s*<')
INC = re.compile(r'#include\s*"([^"]+)"')
LIT = re.compile(r'(?<![\w.])((?:\d+\.\d*|\.\d+)(?:[eE][-+]?\d+)?|\d+[eE][-+]?\d+)(?![\w.])')


def resolve(name, cur):
    for base in (os.path.dirname(cur), libdir, here):
        p = os.path.join(base, name)
        if os.path.exists(p):
            return os.path.normpath(p)
    raise FileNotFoundError(name)


def inline(path):
    path = os.path.normpath(path)
    if path in seen:
        return ''
    seen.add(path)
    out = []
    for line in open(path):
        if SYS.match(line.strip()) or line.strip() == '#pragma once':
            continue
        m = INC.match(line.strip())
        if m:
            out.append(inline(resolve(m.group(1), path)))
            continue
        out.append(line)
    return ''.join(out)


def to_f32(src):
    res = []
    for line in src.splitlines(keepends=True):
        code, sep, comment = line.partition('//')
        code = re.sub(r'\bdouble\b', 'float', code)
        code = LIT.sub(lambda m: m.group(1) + 'f', code)
        res.append(code + sep + comment)
    s = ''.join(res)
    s = s.replace('extern "C" {', 'namespace exported {', 1)
    return s


body = to_f32(inline(os.path.join(here, 'ejk_int3c2e_ip1.cu')))
# whole-program compilation (no -rdc): every extern __constant__/__device__ declaration becomes a definition in this
# translation unit (roots tables from rys_roots_dat.cu, constants from rys_constant.cu, the fold tables unused here)
dat = to_f32(inline(os.path.join(here, 'rys_roots_dat.cu')))
const = to_f32(inline(os.path.join(here, 'rys_constant.cu')))
lines = body.splitlines(keepends=True)
out, put_const, put_dat = [], False, False
for ln in lines:
    t = ln.strip()
    if t.startswith('extern __constant__'):
        if 'c_i_in_fold2idx' in t:
            out.append('__constant__ Fold2Index c_i_in_fold2idx[165];\n')
        elif 'c_i_in_fold3idx' in t:
            out.append('__constant__ Fold3Index c_i_in_fold3idx[495];\n')
        elif not put_const:
            out.append(const)
            put_const = True
        continue
    if t.startswith('extern __device__'):
        if not put_dat:
            out.append(dat)
            put_dat = True
        continue
    out.append(ln)
assert put_const and put_dat
body = ''.join(out)
dat = ''
hdr = '''// GENERATED by gen_f32.py from ejk_int3c2e_ip1.cu and its includes -- do not edit
#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>
#include <stddef.h>
#include <float.h>
#include <cuda.h>
#include <cuda_runtime.h>
namespace rysf32 {
'''
tail = '''
} // namespace rysf32

extern "C" int sum_ejk_int3c2e_ip1_f32(float *ejk, float *ejk_aux, float *dm, float *density_auxvec, int n_dm,
                    float omega, float lr_factor, float sr_factor,
                    rysf32::RysIntEnvVars *envs, int shm_size, int nbatches_shl_pair,
                    int nbatches_ksh, int *shl_pair_offsets, uint32_t *bas_ij_idx,
                    int *ksh_offsets, int *gout_stride_lookup,
                    int *ao_pair_loc, int aux_offset,
                    int nao, int npairs, int naux, int natm)
{
    return rysf32::exported::sum_ejk_int3c2e_ip1(ejk, ejk_aux, dm, density_auxvec, n_dm, omega, lr_factor, sr_factor,
        envs, shm_size, nbatches_shl_pair, nbatches_ksh, shl_pair_offsets, bas_ij_idx, ksh_offsets,
        gout_stride_lookup, ao_pair_loc, aux_offset, nao, npairs, naux, natm);
}
'''
# rys_roots_dat.cu content must come after the extern declarations of rys_roots.cuh (inside the body); append it
open(os.path.join(here, 'ejk_int3c2e_ip1_f32.cu'), 'w').write(hdr + body + '\n' + dat + tail)
print('written ejk_int3c2e_ip1_f32.cu')
